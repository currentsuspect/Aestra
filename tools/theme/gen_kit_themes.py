#!/usr/bin/env python3
"""Writes AestraUI/Core/NUIKitThemes.inc from the Aestra Kit's resolved theme values (FD-79).

The kit (gen.py, outside this repository) is where theme colours are designed and contrast-checked; it writes
resolved.json with every token of all twelve variants. This script turns that file into a C++ table so the app
carries exactly the values the Design Spec shows. Run it whenever the kit's values change:

    python3 tools/theme/gen_kit_themes.py path/to/resolved.json
"""
import json
import pathlib
import sys

# Depth and glass tokens, per mode. They are the Design Spec's own values (its vars()), not the kit's, because the
# kit predates the depth rule. Light comes from above: neuLo is the shade on the top-left inner edge of a well,
# neuHi the faint highlight opposite; neuEdge is the high-contrast inner edge that keeps a control findable.
DEPTH = {
    "dark": {"neuHi": "#ffffff0e", "neuLo": "#000000d9", "neuEdge": "#00000000",
             "glassHi": "#ffffff1a", "glassEdge": "#ffffff26", "glassShade": "#000000b3"},
    "light": {"neuHi": "#ffffffe6", "neuLo": "#0000002b", "neuEdge": "#00000000",
              "glassHi": "#ffffffa6", "glassEdge": "#ffffffd9", "glassShade": "#00000024"},
    "hc": {"neuHi": "#ffffff26", "neuLo": "#000000ff", "neuEdge": None,  # borderSubtle
           "glassHi": "#ffffff14", "glassEdge": "#ffffff33", "glassShade": "#000000ff"},
}


def rgba(hex_value: str) -> str:
    h = hex_value.lstrip("#")
    if len(h) == 6:
        h += "ff"
    if len(h) != 8:
        raise ValueError(f"not a colour: {hex_value}")
    return "0x" + h.lower() + "u"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    data = json.loads(pathlib.Path(sys.argv[1]).read_text())
    out = [
        "// Generated by tools/theme/gen_kit_themes.py from the Aestra Kit's resolved.json. Do not edit by hand.",
        "// Each entry: key, theme name, mode name, mode (0 dark, 1 light, 2 high contrast), then name/RGBA pairs.",
        "// clang-format off",
    ]
    for key in data["order"]:
        family, mode = key.rsplit("-", 1)
        values = dict(data["values"][key])
        for name, value in DEPTH[mode].items():
            values[name] = value if value is not None else values["borderSubtle"]
        pairs = ", ".join(f'{{"{n}", {rgba(v)}}}' for n, v in values.items())
        mode_index = {"dark": 0, "light": 1, "hc": 2}[mode]
        out.append(f'AESTRA_KIT_THEME("{key}", "{data["names"][family]}", "{data["modes"][mode]}", {mode_index}, {pairs})')
    out.append("// clang-format on")
    target = pathlib.Path(__file__).resolve().parents[2] / "AestraUI" / "Core" / "NUIKitThemes.inc"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target} ({len(data['order'])} themes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
