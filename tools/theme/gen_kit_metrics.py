#!/usr/bin/env python3
"""Writes AestraUI/Core/NUIKitMetrics.inc from the Aestra Kit's tokens.json (spacing group).

The kit (outside this repository) is where the spacing scale is designed. This script turns its `spacing` group
into one AESTRA_KIT_SPACING line per token so the app carries exactly the kit's steps. Run it whenever the kit's
spacing changes:

    python3 tools/theme/gen_kit_metrics.py path/to/tokens.json

Only spacing is generated so far; the other families (radius, shadow, duration, ...) are not read yet.
"""
import json
import pathlib
import re
import sys

# The scale the app expects, smallest first. NUIKitMetrics in NUIThemeSystem.h indexes by this order.
ORDER = ["xxs", "xs", "s", "m", "l", "xl", "xxl"]


def px(value: str) -> int:
    m = re.fullmatch(r"(\d+)px", value.strip())
    if not m:
        raise ValueError(f"not a pixel value: {value!r}")
    return int(m.group(1))


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    data = json.loads(pathlib.Path(sys.argv[1]).read_text())
    steps = {}
    for token in data["spacing"]["tokens"]:
        name = token["name"]
        if not name.startswith("space-"):
            raise ValueError(f"unexpected spacing token {name!r}")
        steps[name[len("space-"):]] = px(token["value"])
    if sorted(steps) != sorted(ORDER):
        raise ValueError(f"spacing tokens {sorted(steps)} do not match the expected scale {ORDER}")
    values = [steps[n] for n in ORDER]
    if values != sorted(set(values)):
        raise ValueError(f"spacing is not strictly increasing: {values}")
    out = [
        "// Generated by tools/theme/gen_kit_metrics.py from the Aestra Kit's tokens.json. Do not edit by hand.",
        "// One line per spacing token, smallest first: AESTRA_KIT_SPACING(step, pixels).",
        "// clang-format off",
    ]
    out += [f"AESTRA_KIT_SPACING({n}, {steps[n]}.0f)" for n in ORDER]
    out.append("// clang-format on")
    target = pathlib.Path(__file__).resolve().parents[2] / "AestraUI" / "Core" / "NUIKitMetrics.inc"
    target.write_text("\n".join(out) + "\n")
    print(f"wrote {target} ({len(ORDER)} spacing steps)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
