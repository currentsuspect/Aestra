#!/usr/bin/env node
// Writes Tests/Headless/RumbleVoiceGolden.inc: what the approved Rumble sketch (FD-80, SPEC-025 R2) plays
// for a set of fixed sounds, so the C++ voice can be held to it sample for sample.
//
// render() below is copied unchanged from the sketch (claude.ai/artifact/LD4nr3DXP7BiLtLmhX8cAG, version 2;
// vault: 17 Specifications/SPEC-025 Rumble sketch source.html). Do not "improve" it: it is the reference.
//
//   node tools/rumble/sketch_golden.js > Tests/Headless/RumbleVoiceGolden.inc
const TMAX = 3.9;
var tailSec = function (n) { return 0.25 * Math.pow(14, n); };
var toneHz = function (n) { return 90 * Math.pow(60, n); };
function dropTime(g) { var d = Math.max(.2, g.punch * 30); return Math.min(.012 + g.ptime * .11, .35 * (.02 + g.hold * .18 + tailSec(g.tail)) / Math.log(d / .1)); }
function shape(x, c) { if (c < .34) return Math.tanh(x); if (c < .67) return x > 1 ? 1 : x < -1 ? -1 : x; return Math.sin(x * 1.2); }
function render(g, midi, sr) {
  var f0 = 440 * Math.pow(2, (midi - 69) / 12), t60 = tailSec(g.tail), hold = .02 + g.hold * .18;
  var len = Math.min(TMAX + .3, hold + t60 + .03), n = Math.floor(len * sr), out = new Float32Array(n);
  var drop = g.punch * 30, pt = dropTime(g), cv = .6 + g.curve * 1.2, drive = 1 + g.dirt * g.dirt * 22;
  var cut = toneHz(g.tone), ph = 0, l1 = 0, l2 = 0, cl = 0, seed = g.seed >>> 0, tp = 2 * Math.PI;
  var ca = 1 - Math.exp(-tp * (400 + g.ctone * 5000) / sr), cd = .002 + g.clen * .02, peak = 0;
  for (var i = 0; i < n; i++) {
    var t = i / sr, f = f0 * Math.pow(2, drop * Math.exp(-t / pt) / 12);
    ph += tp * f / sr;
    var te = t < hold ? 0 : (t - hold) / t60, env = Math.exp(-6.9 * Math.pow(te, cv));
    var s = Math.sin(ph) + g.h2 * .6 * Math.sin(2 * ph + .6) + g.h3 * .45 * Math.sin(3 * ph);
    var x = s * env * (1 + g.punch * .6 * Math.exp(-t / .03));
    var dv = shape(x * drive, g.clip);
    var a = 1 - Math.exp(-tp * Math.min(sr * .45, cut * (.3 + .7 * env) + f0 * 1.5) / sr);
    l1 += a * (dv - l1); l2 += a * (l1 - l2);
    seed = (seed * 1664525 + 1013904223) >>> 0; var nz = seed / 2147483648 - 1;
    cl += ca * (nz - cl);
    var ck = (cl * (1 - g.ctone) + (nz - cl) * g.ctone * .5) * g.click * Math.exp(-t / cd) * .9;
    var v = Math.min(1, t / .0015) * (l2 * (1 - .45 * g.weight) + Math.sin(ph) * env * g.weight * .9 + ck);
    out[i] = v; if (v > peak) peak = v; else if (-v > peak) peak = -v;
  }
  var gain = .85 / (peak || 1), fade = Math.floor(.008 * sr);
  for (i = 0; i < n; i++) out[i] *= gain * (i > n - fade ? (n - i) / fade : 1);
  return { out: out, peak: peak };
}

// The sketch's seven starts, then sounds spread over the whole range by a fixed generator.
const KEYS = ['punch', 'tail', 'weight', 'tone', 'dirt', 'slide', 'ptime', 'hold', 'curve', 'h2', 'h3', 'clip', 'click', 'clen', 'ctone'];
const base = { punch: .42, tail: .55, weight: .5, tone: .5, dirt: .3, slide: 0, ptime: .35, hold: .3, curve: .5, h2: .3, h3: .2, clip: .1, click: .35, clen: .3, ctone: .4 };
const starts = [{}, { punch: .15, tail: .6, weight: .88, tone: .25, dirt: .04, click: .08, h2: .1, h3: .05 }, { punch: .75, tail: .2, weight: .4, tone: .6, dirt: .35, click: .7, ptime: .2 },
  { punch: .3, tail: .9, weight: .62, tone: .4, dirt: .2, curve: .7 }, { punch: .5, tail: .76, weight: .7, tone: .2, dirt: .46, ptime: .6 },
  { punch: .55, tail: .6, weight: .3, tone: .76, dirt: .86, clip: .5, h3: .5 }, { punch: .25, tail: .66, weight: .35, tone: .7, dirt: .5, slide: .5, h2: .5 }];
let rs = 2026; const rnd = () => { rs = (rs * 1103515245 + 12345) % 2147483648; return rs / 2147483648; };
const cases = [];
starts.forEach((o, i) => cases.push({ g: Object.assign({}, base, o, { seed: 1000 + i }), midi: 29, sr: 48000 }));
for (let i = 0; i < 17; i++) {
  const g = { seed: Math.floor(rnd() * 4294967295) }; KEYS.forEach(k => { g[k] = Math.round(rnd() * 1000) / 1000; });
  if (i % 4 === 0) g.clip = [.1, .5, .9][i % 3]; // every saturation type
  cases.push({ g, midi: 21 + Math.floor(rnd() * 24), sr: i % 3 === 0 ? 44100 : 48000 });
}
const lit = v => { const t = String(v); return /[.e]/.test(t) ? t : t + '.0'; };
const STRIDE = 193;
const L = [];
L.push('// Generated by tools/rumble/sketch_golden.js from the approved Rumble sketch. Do not edit by hand.');
L.push('// Each case: the sound, the note, the sample rate, the length, the raw peak, and every 193rd sample of the');
L.push('// finished (levelled, faded) sound.');
L.push('struct RumbleGoldenCase { double s[15]; uint32_t seed; int note; double rate; uint32_t length; double peak; uint32_t stride; std::vector<float> samples; };');
L.push('inline const std::vector<RumbleGoldenCase>& rumbleGoldenCases() {');
L.push('    static const std::vector<RumbleGoldenCase> cases = {');
for (const c of cases) {
  const r = render(c.g, c.midi, c.sr), pts = [];
  for (let i = 0; i < r.out.length; i += STRIDE) pts.push(r.out[i].toPrecision(9));
  L.push('        {{' + KEYS.map(k => lit(c.g[k])).join(', ') + '}, ' + (c.g.seed >>> 0) + 'u, ' + c.midi + ', ' + c.sr + '.0, ' + r.out.length + 'u, ' + r.peak.toPrecision(17) + ', ' + STRIDE + 'u,');
  L.push('         {' + pts.map(p => p + 'f').join(', ') + '}},');
}
L.push('    };');
L.push('    return cases;');
L.push('}');
console.log(L.join('\n'));
