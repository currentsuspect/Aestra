#!/usr/bin/env node
// Writes Tests/Headless/RumbleOutlineGolden.inc: the outline the approved Rumble sketch draws for a set of fixed
// sounds (SPEC-025 R3), so the C++ outline can be held to it bin for bin.
//
// render() is taken from sketch_golden.js (copied unchanged from the sketch); peaks() below is the sketch's
// own, with only its cache and the page's sample rate turned into arguments. Do not "improve" either.
//
//   node tools/rumble/sketch_outline_golden.js > Tests/Headless/RumbleOutlineGolden.inc
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, 'sketch_golden.js'), 'utf8');
const sketch = new Function(src.slice(src.indexOf('const TMAX'), src.indexOf("// The sketch's seven starts")) +
  'return { render: render, TMAX: TMAX };')();
const TMAX = sketch.TMAX, ROOT = 29;
const render = (g, midi, sr) => sketch.render(g, midi, sr).out;

function peaks(g, sr) {
  var b = render(g, ROOT, sr), N = 260, pk = new Float32Array(N);
  for (var j = 0; j < N; j++) {
    var i0 = Math.floor(Math.pow(j / N, 2) * TMAX * sr), i1 = Math.max(i0 + 1, Math.floor(Math.pow((j + 1) / N, 2) * TMAX * sr)), m = 0;
    for (var i = i0; i < i1 && i < b.length; i += 3) { var v = b[i] < 0 ? -b[i] : b[i]; if (v > m) m = v; }
    pk[j] = m;
  }
  return pk;
}

// The bank's seven starts (as the sketch has them now), then sounds spread over the whole range.
const base = { punch: .42, tail: .55, weight: .5, tone: .5, dirt: .3, slide: 0, ptime: .35, hold: .3, curve: .5, h2: .3, h3: .2, clip: .1, click: .35, clen: .3, ctone: .4 };
const starts = [{},
  { punch: .15, tail: .6, weight: .88, tone: .25, dirt: .04, click: .08, h2: .1, h3: .05 },
  { punch: .55, tail: .3, weight: .72, tone: .5, dirt: .4, click: .6, ptime: .25, hold: .5, curve: .85 },
  { punch: .3, tail: .9, weight: .62, tone: .4, dirt: .2, curve: .7 },
  { punch: .5, tail: .76, weight: .7, tone: .2, dirt: .46, ptime: .6 },
  { punch: .55, tail: .6, weight: .3, tone: .76, dirt: .86, clip: .5, h3: .5 },
  { punch: .25, tail: .66, weight: .35, tone: .7, dirt: .5, h2: .5, slide: .5 }];
const cases = starts.map((o, i) => ({ g: Object.assign({}, base, o, { seed: 1000 + i }), sr: 48000 }));
let rs = 4242;
const rnd = () => { rs = (rs * 1103515245 + 12345) >>> 0; return rs / 4294967296; };
const KEYS = ['punch', 'tail', 'weight', 'tone', 'dirt', 'slide', 'ptime', 'hold', 'curve', 'h2', 'h3', 'clip', 'click', 'clen', 'ctone'];
for (let i = 0; i < 6; i++) {
  const g = { seed: 2000 + i };
  KEYS.forEach(k => { g[k] = Math.round(rnd() * 1000) / 1000; });
  cases.push({ g, sr: i % 2 ? 44100 : 48000 });
}

const f = x => (Number.isInteger(x) ? x.toFixed(1) : String(x));
const out = ['// Generated by tools/rumble/sketch_outline_golden.js from the approved Rumble sketch. Do not edit by hand.',
  '// Each case: the sound, its seed, the sample rate, and the 260 outline bins the sketch draws.',
  'struct RumbleOutlineGoldenCase { double s[15]; uint32_t seed; double rate; std::vector<float> bins; };',
  'inline const std::vector<RumbleOutlineGoldenCase>& rumbleOutlineGoldenCases() {',
  '    static const std::vector<RumbleOutlineGoldenCase> cases = {'];
for (const c of cases) {
  const pk = Array.from(peaks(c.g, c.sr)).map(v => v.toPrecision(9) + 'f');
  out.push('        {{' + KEYS.map(k => f(c.g[k])).join(', ') + '}, ' + c.g.seed + 'u, ' + f(c.sr) + ',');
  out.push('         {' + pk.join(', ') + '}},');
}
out.push('    };', '    return cases;', '}');
console.log(out.join('\n'));
